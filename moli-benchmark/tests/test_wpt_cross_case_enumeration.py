            for prefixes in (None, ("dom",)):
                with self.subTest(dir_prefixes=prefixes):
                    self.assertEqual(
                        enumerate_cases(wpt_root, dir_prefixes=prefixes), expected
                    )
                    self.assertEqual(
                        enumerate_cases(wpt_root, dir_prefixes=prefixes, limit=1),
                        expected[:1],
                    )
