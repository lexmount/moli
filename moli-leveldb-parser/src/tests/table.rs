#[test]
fn truncated_footer_and_bad_magic() {
    for length in 0..48 {
        assert!(scan(&[0; 48][..length]).is_err());
    }
    let mut bytes = table(&[], 1, 1, 0);
    let length = bytes.len();
    bytes[length - 1] ^= 1;
    assert!(scan(&bytes).unwrap_err().to_string().contains("magic"));
}

