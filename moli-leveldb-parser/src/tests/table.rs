#[test]
fn randomized() -> Result<()> {
    // Same entry-count schedule, key alphabet and skewed lengths as Harness.
    let mut random = Random::new(306);
    for count in (0..50).chain((50..2000).step_by(200)) {
        let mut entries = Entries::new();
        for _ in 0..count {
            let key_length = random.skewed(4);
            let key = random.key(key_length);
            let value_length = random.skewed(5);
            entries.insert(key, random.string(value_length));
        }
        check(&entries)?;
    }
    Ok(())
}

#[test]
fn randomized_long_db() -> Result<()> {
    // Generated by Chromium's pinned C++ engine. The Rust fixture engine panics
    // in its shortest-separator routine for empty keys during this workload.
    let directory = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/chromium/randomized-long-db");
    let mut random = Random::new(301);
    let mut expected = Entries::new();
    for _ in 0..100_000 {
        let key_length = random.skewed(4);
        let key = random.key(key_length);
        let value_length = random.skewed(5);
        let value = random.string(value_length);
        expected.insert(key, value);
    }
    assert!(
        !crate::manifest::Manifest::read(&directory)?
            .tables
            .is_empty()
    );
    assert_eq!(read_snapshot(&directory)?, expected);
    Ok(())
}

#[test]
fn approximate_offset_of_plain_read_contents() -> Result<()> {
    // Keep upstream's large-value/block-boundary workload; this parser exposes
    // a full scan, so validate contents instead of a writer's offset estimate.
    let entries = vec![
        (b"k01".to_vec(), b"hello".to_vec()),
        (b"k02".to_vec(), b"hello2".to_vec()),
        (b"k03".to_vec(), vec![b'x'; 10_000]),
        (b"k04".to_vec(), vec![b'x'; 200_000]),
        (b"k05".to_vec(), vec![b'x'; 300_000]),
        (b"k06".to_vec(), b"hello3".to_vec()),
        (b"k07".to_vec(), vec![b'x'; 100_000]),
    ];
    assert_eq!(scan(&table(&entries, 16, 2, 0))?, entries);
    Ok(())
}

#[test]
fn approximate_offset_of_compressed_read_contents() -> Result<()> {
    let mut random = Random::new(301);
    let first = big_string(&random.string(2500), 10_000);
    let second = big_string(&random.string(2500), 10_000);
    let entries = vec![
        (b"k01".to_vec(), b"hello".to_vec()),
        (b"k02".to_vec(), first),
        (b"k03".to_vec(), b"hello3".to_vec()),
        (b"k04".to_vec(), second),
    ];
    let compressed = table(&entries, 16, 2, 1);
    assert!(compressed.len() < 10_000);
    assert_eq!(scan(&compressed)?, entries);
    Ok(())
}

#[test]
fn internal_key_encode_decode() -> Result<()> {
    let directory = tempfile::tempdir()?;
    let sequences = [
        1,
        2,
        3,
        (1 << 8) - 1,
        1 << 8,
        (1 << 8) + 1,
        (1 << 16) - 1,
        1 << 16,
        (1 << 16) + 1,
        (1 << 32) - 1,
        1 << 32,
        (1 << 32) + 1,
        MAX_SEQUENCE,
    ];
    for sequence in sequences {
        let mut edit = metadata(3, sequence);
        let entries: Vec<_> = [b"".as_slice(), b"k", b"hello", b"longggggggggggggggggggggg"]
            .into_iter()
            .map(|key| (internal_key(key, sequence, 1), b"value".to_vec()))
            .collect();
        // The data reader consumes the on-disk order; public output is bytewise.
        let mut entries = entries;
        entries.sort_by(|a, b| a.0[..a.0.len() - 8].cmp(&b.0[..b.0.len() - 8]));
        save_table(directory.path(), &mut edit, 0, 4, &entries)?;
        write_manifest(directory.path(), &[edit])?;
        let expected: Entries = [b"".as_slice(), b"k", b"hello", b"longggggggggggggggggggggg"]
            .into_iter()
            .map(|key| (key.to_vec(), b"value".to_vec()))
            .collect();
        assert_eq!(read_snapshot(directory.path())?, expected);
        let mut edit = metadata(3, sequence);
        save_table(
            directory.path(),
            &mut edit,
            0,
            4,
            &[(internal_key(b"hello", sequence, 0), vec![])],
        )?;
        write_manifest(directory.path(), &[edit])?;
        assert!(read_snapshot(directory.path())?.is_empty());
    }
    Ok(())
}

#[test]
fn internal_key_decode_from_empty() -> Result<()> {
    let directory = tempfile::tempdir()?;
    for length in 0..8 {
        let bytes = table(&[(vec![b'k'; length], b"value".to_vec())], 1, 1, 0);
        fs::write(directory.path().join("000004.ldb"), &bytes)?;
        let mut edit = metadata(3, 1);
        let key = internal_key(b"key", 1, 1);
        add_table(&mut edit, 0, 4, bytes.len() as u64, &key, &key);
        write_manifest(directory.path(), &[edit])?;
        assert!(
            format!("{:#}", read_snapshot(directory.path()).unwrap_err()).contains("internal key")
        );
    }
    Ok(())
}

