fn scan(bytes: &[u8]) -> Result<Vec<(Vec<u8>, Vec<u8>)>> {
    let directory = tempfile::tempdir()?;
    let path = directory.path().join("table.ldb");
    fs::write(&path, bytes)?;
    let mut result = Vec::new();
    read_table(&path, bytes.len() as u64, |key, value| {
        result.push((key.to_vec(), value.to_vec()));
        Ok(())
    })?;
    Ok(result)
}

fn check(entries: &Entries) -> Result<()> {
    let expected: Vec<_> = entries
        .iter()
        .map(|(k, v)| (k.clone(), v.clone()))
        .collect();
    for restart_interval in [1, 16, 1024] {
        let mut actual = Vec::new();
        read_entries(&block(&expected, restart_interval), |k, v| {
            actual.push((k.to_vec(), v.to_vec()));
            Ok(())
        })?;
        assert_eq!(actual, expected, "restart interval {restart_interval}");
        for compression in [0, 1] {
            let bytes = table(&expected, restart_interval, 13, compression);
            assert_eq!(
                scan(&bytes)?,
                expected,
                "restart interval {restart_interval}, compression {compression}"
            );
        }
    }
    Ok(())
}

