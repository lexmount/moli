#[derive(Clone, Copy, PartialEq, Eq)]
pub(in crate::context_bootstrap) enum ConstructorPrototypeProperty {
    TemplateReadOnly,
    RuntimeInstalled { prototype_interface: &'static str },
}

#[derive(Clone, Copy)]
pub(in crate::context_bootstrap) struct ConstructorSpec {
    pub(in crate::context_bootstrap) name: &'static str,
    pub(in crate::context_bootstrap) parent: Option<&'static str>,
    pub(in crate::context_bootstrap) kind: ConstructorKind,
}

impl ConstructorSpec {
    pub(in crate::context_bootstrap) fn prototype_property(self) -> ConstructorPrototypeProperty {
        match self.kind {
            // HTML exposes these names as WebIDL LegacyFactoryFunction objects,
            // not as independent interface constructors. Their public
            // `prototype` property points at the backing element interface
            // prototype and must be installed after both objects exist.
            ConstructorKind::Audio => ConstructorPrototypeProperty::RuntimeInstalled {
                prototype_interface: "HTMLAudioElement",
            },
            ConstructorKind::Image => ConstructorPrototypeProperty::RuntimeInstalled {
                prototype_interface: "HTMLImageElement",
            },
            ConstructorKind::Option => ConstructorPrototypeProperty::RuntimeInstalled {
                prototype_interface: "HTMLOptionElement",
            },
            _ => ConstructorPrototypeProperty::TemplateReadOnly,
        }
    }
}
