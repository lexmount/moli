use std::sync::LazyLock;

use super::config::{Configuration, ElementAttributes, Filter, HTML, MATHML, Name, SVG};

pub(super) static DEFAULT_CONFIGURATION: LazyLock<Configuration> = LazyLock::new(|| {
    let elements = [
        (HTML, HTML_ELEMENTS),
        (MATHML, MATHML_ELEMENTS),
        (SVG, SVG_ELEMENTS),
    ]
    .into_iter()
    .flat_map(|(namespace, elements)| {
        elements.iter().map(move |(name, attributes)| {
            (
                Name::new(name, Some(namespace)),
                ElementAttributes {
                    allow: Some(
                        attributes
                            .iter()
                            .map(|name| Name::new(name, None))
                            .collect(),
                    ),
                    remove: None,
                },
            )
        })
    })
    .collect();
    Configuration {
        elements: Filter::Allow(elements),
        attributes: Filter::Allow(
            GLOBAL_ATTRIBUTES
                .iter()
                .map(|name| Name::new(name, None))
                .collect(),
        ),
        processing_instructions: Filter::Allow(Default::default()),
        replace_with_children: None,
        comments: false,
        data_attributes: Some(false),
        javascript_urls: false,
    }
});

